export function generateChapterPrompt(
  animeTitle: string,
  synopsis: string,
  chapterNumber: number,
  previousContent?: string
): string {
  let prompt = `Ты талантливый писатель, специализирующийся на создании продолжений аниме в стиле ранобэ.

Название аниме: ${animeTitle}
Оригинальный сюжет: ${synopsis}

Напиши главу ${chapterNumber} продолжения этого аниме.

Требования:
1. Стиль должен соответствовать японским ранобэ
2. Сохраняй атмосферу и характеры оригинала
3. Добавляй диалоги, описания и развитие сюжета
4. Глава должна быть увлекательной и захватывающей
5. Используй красивые литературные описания

Формат вывода:
- Сначала заголовок главы
- Затем основной текст
- Используй markdown для форматирования`;

  if (previousContent) {
    prompt += `\n\nПредыдущая глава:\n${previousContent}\n\nПродолжай историю, учитывая события предыдущей главы.`;
  }

  return prompt;
}
